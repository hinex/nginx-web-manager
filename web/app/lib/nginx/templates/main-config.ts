/**
 * The main nginx.conf, as a pure function of its settings so it can be tested
 * without a database or filesystem.
 */

export const MAP_HASH_MAX_SIZE_KEY = "map_hash_max_size";
export const MAP_HASH_BUCKET_SIZE_KEY = "map_hash_bucket_size";
export const DEFAULT_MAP_HASH_MAX_SIZE = 8192;
export const DEFAULT_MAP_HASH_BUCKET_SIZE = 128;

/** Upper bound for either hash setting - well past any real map, and far below overflow. */
export const MAX_HASH_SIZE = 16_777_216;

export interface MainConfigOptions {
  mapHashMaxSize: number;
  mapHashBucketSize: number;
}

/**
 * Validates a hash-size setting. Returns the integer, or null when the value
 * is not a positive whole number within MAX_HASH_SIZE.
 */
export function validateHashSize(raw: string): number | null {
  const trimmed = raw.trim();
  if (!/^[0-9]+$/.test(trimmed)) return null;
  const n = Number(trimmed);
  if (n < 1 || n > MAX_HASH_SIZE) return null;
  return n;
}

/**
 * Reads a stored hash-size setting, falling back to the default when it is
 * unset, empty or invalid - nginx.conf must always render to something nginx
 * accepts, whatever is in the settings table.
 */
export function parseHashSize(raw: string | null | undefined, fallback: number): number {
  if (raw == null || raw.trim() === "") return fallback;
  return validateHashSize(raw) ?? fallback;
}

export function renderMainConfig(opts: MainConfigOptions): string {
  return `# Auto-generated by Nginx Manager. Do not edit manually.
worker_processes auto;
worker_rlimit_nofile 65535;
error_log /data/logs/error.log warn;
pid /run/nginx.pid;

events {
    worker_connections 4096;
    multi_accept on;
    use epoll;
}

http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;

    log_format main '$remote_addr - $remote_user [$time_local] "$request" '
                    '$status $body_bytes_sent "$http_referer" '
                    '"$http_user_agent" "$http_x_forwarded_for"';

    access_log /data/logs/access.log main buffer=16k flush=5s;

    # Performance
    sendfile on;
    tcp_nopush on;
    tcp_nodelay on;
    keepalive_timeout 65;
    keepalive_requests 1000;
    reset_timedout_connection on;
    types_hash_max_size 2048;
    server_names_hash_bucket_size 128;
    client_max_body_size 100m;

    # Proxy defaults
    proxy_connect_timeout 60s;
    proxy_send_timeout 60s;
    proxy_read_timeout 60s;
    proxy_buffering on;
    proxy_buffer_size 4k;
    proxy_buffers 8 16k;
    proxy_busy_buffers_size 32k;

    # Gzip
    gzip on;
    gzip_vary on;
    gzip_proxied any;
    gzip_comp_level 4;
    gzip_min_length 256;
    gzip_types text/plain text/css text/xml application/json application/javascript application/xml+rss application/atom+xml image/svg+xml application/xhtml+xml font/woff2;

    # Map hash sizing. nginx fixes these when it parses the first map block
    # below, so they must stay ahead of it and of the host includes - set
    # anywhere later they are rejected as "duplicate" (NUANCES #68).
    map_hash_max_size ${opts.mapHashMaxSize};
    map_hash_bucket_size ${opts.mapHashBucketSize};

    # Request id: prefer the upstream's own X-Request-Id
    map $upstream_http_x_request_id $req_id {
        default $upstream_http_x_request_id;
        ""      $request_id;
    }

    include /data/nginx/conf.d/*.conf;
}

stream {
    include /data/nginx/stream.d/*.conf;
}
`;
}
